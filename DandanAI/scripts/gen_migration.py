import sys

sys.path.insert(0, os.getcwd())
from sqlalchemy.dialects import postgresql  # noqa: E402
from sqlalchemy.schema import CreateIndex, CreateTable  # noqa: E402

from app import models  # noqa: E402,F401
from app.database import Base  # noqa: E402

d = postgresql.dialect()
up = ['op.execute("CREATE EXTENSION IF NOT EXISTS vector")']
for t in Base.metadata.sorted_tables:
    up.append(f"op.execute({str(CreateTable(t).compile(dialect=d)).strip()!r})")
    for ix in sorted(t.indexes, key=lambda i: i.name):
        up.append(f"op.execute({str(CreateIndex(ix).compile(dialect=d)).strip()!r})")
up += ['op.execute("CREATE INDEX ix_legal_chunks_embedding_hnsw ON legal_chunks USING hnsw (embedding vector_cosine_ops)")',
       'op.execute("CREATE INDEX ix_document_chunks_embedding_hnsw ON document_chunks USING hnsw (embedding vector_cosine_ops)")',
       "op.execute(\"CREATE INDEX ix_legal_chunks_fts ON legal_chunks USING gin (to_tsvector('english', text))\")"]
down = [f'op.execute("DROP TABLE IF EXISTS {t.name} CASCADE")' for t in reversed(Base.metadata.sorted_tables)]
body = '"""initial schema (generated by scripts/gen_migration.py)"""\nfrom alembic import op\n\nrevision = "0001"\ndown_revision = None\nbranch_labels = None\ndepends_on = None\n\n\ndef upgrade() -> None:\n' + \
    "\n".join("    " + u for u in up) + "\n\n\ndef downgrade() -> None:\n" + "\n".join("    " + x for x in down) + "\n"
open("alembic/versions/0001_initial.py", "w").write(body)
print("tables:", len(Base.metadata.sorted_tables))
